import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash,createPublicKey,verify} from 'node:crypto';
import {readFile} from 'node:fs/promises';
const ROOT=new URL('../',import.meta.url);
const json=async p=>JSON.parse(await readFile(new URL(p,ROOT),'utf8'));
const canonical=v=>Array.isArray(v)?'['+v.map(canonical).join(',')+']':v&&typeof v==='object'?'{'+Object.keys(v).sort().map(k=>JSON.stringify(k)+':'+canonical(v[k])).join(',')+'}':JSON.stringify(v);
const gitBlob=v=>{const b=Buffer.from(JSON.stringify(v,null,2)+'\n','utf8');return createHash('sha1').update('blob '+b.length+'\0').update(b).digest('hex');};
const oldBlob='fe27a61ef895ea9734a9e4096e2419f203dcde32';
const proposedBlob='b7d244041fce2d41a4ece7f46f3266b393c85546';
const newVersion='access-p1-20261018062951Z';
test('CLB-01 owner ES256 signature is valid with pinned existing Studio trust anchor, not a new self-signed key',async()=>{
 const [bundle,sig,trust,policy]=await Promise.all(['src/config/access-config-bundle.json','src/config/access-config-bundle.sig.json','src/config/access-config-verify-key.json','src/config/access-policy.json'].map(json));
 assert.equal(bundle.schema,'ghrab-access-config-bundle-v1');
 assert.equal(bundle.version,newVersion);
 assert.equal(sig.schema,'ghrab-access-config-signature-v1');
 assert.equal(sig.algorithm,'ES256');
 assert.equal(sig.keyId,'ghrab-access-bundle-20260822195407Z-fxjS8DK9');
 assert.equal(sig.keyId,trust.keyId);
 assert.equal(sig.bundleVersion,bundle.version);
 assert.equal(trust.publicKey.kty,'EC');
 assert.equal(trust.publicKey.crv,'P-256');
 const signature=Buffer.from(sig.signature,'base64url');
 assert.equal(signature.length,64);
 const pub=createPublicKey({key:trust.publicKey,format:'jwk'});
 const raw=Buffer.from(canonical(bundle),'utf8');
 assert.equal(verify('sha256',raw,{key:pub,dsaEncoding:'ieee-p1363'},signature),true);
 const tampered=structuredClone(bundle);
 tampered.policy.applications['conversation-lab'].trainingCode='GEN-01';
 assert.equal(verify('sha256',Buffer.from(canonical(tampered),'utf8'),{key:pub,dsaEncoding:'ieee-p1363'},signature),false);
 assert.deepEqual(bundle.policy,policy);
});
test('CLB-01 signed proposal changes only version, issuing timestamps, and one training policy entry',async()=>{
 const [bundle,policy,staged]=await Promise.all(['src/config/access-config-bundle.json','src/config/access-policy.json','src/integration/conversation-lab/access-policy.ready-for-signing.json'].map(json));
 assert.equal(bundle.version,newVersion);
 assert.equal(bundle.issuedAt,'2026-10-18T06:29:51.815Z');
 assert.equal(bundle.generatedAt,bundle.issuedAt);
 assert.equal(gitBlob(policy),proposedBlob,'exact human-approved ready-for-signing policy');
 assert.deepEqual(policy,staged);
 assert.equal(Object.keys(policy.applications).length,10);
 assert.deepEqual(policy.applications['conversation-lab'],{trainingRequired:true,trainingCode:'CLB-01',trainingVersion:'2026-10',label:{cs:'Conversation Lab',en:'Conversation Lab'}});
 const old=structuredClone(bundle);
 delete old.policy.applications['conversation-lab'];
 old.version='access-p1-20260923T181737Z';
 old.issuedAt='2026-09-23T18:17:37.404Z';
 old.generatedAt=old.issuedAt;
 assert.equal(gitBlob(old),oldBlob,'legacy nine-app bundle exact byte-equivalence from GitHub history');
 assert.equal(policy.defaultState,'locked');
 assert.equal(policy.offlinePolicy.failClosedWhenStale,true);
 assert.equal(bundle.maxOfflineAgeHours,24);
 assert.equal(bundle.maxSignedBundleAgeDays,30);
});
test('CLB-01 both deployment profiles refer to the exact signed bundle without leaking private key',async()=>{
 const [bundle,github,school,control,activation]=await Promise.all(['src/config/access-config-bundle.json','src/config/deployment.json','src/config/deployment.school-server.json','src/integration/conversation-lab/launch-control.json','src/integration/conversation-lab/activation-gates.json'].map(json));
 assert.equal(github.sharedAccessVersion,bundle.version);
 assert.equal(school.sharedAccessVersion,bundle.version);
 assert.equal(control.stage,'PRELIVE_HOLD');
 assert.equal(control.launchEnabled,false);
 assert.equal(activation.stage,'PRELIVE_HOLD');
 assert.equal(activation.studioManifestActuallyPublished,false);
 assert.equal(activation.launcherEnabled,false);
 assert.equal(activation.signing.accessPolicyBundle,'SIGNED_ON_PRELIVE_BRANCH_NOT_PRODUCTION');
 assert.equal(activation.signing.productionStatement,'OWNER_CONTENT_ES256_SIGNED_NO_INDEPENDENT_SECURITY_GO');
 assert.equal(activation.signing.ownerContentStatementSha256,'77549c561032c35e6c78bb52885ddcc0022d64a7115bb230c8997286e61e8d0a');
 assert.equal(activation.signing.ownerContentSignatureVerified,true);
 assert.equal(activation.garpLive,'NOT_ATTESTED');
 assert.equal(activation.studioP5,'NOT_RUN_FOR_THIS_RELEASE');
 const privateKey=JSON.stringify({bundle,github,school});
 assert.ok(!privateKey.includes('"d":'));
 assert.ok(!privateKey.includes('privateJwk'));
});
